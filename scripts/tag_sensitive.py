#!/usr/bin/env python3
"""标记 sensitive（spec §4.3）—— 建议家长陪读的条目。

判定分两步：先按暴力词命中，再按豁免规则排除。但**两个方向都要审**，
这一点是踩了坑才学会的 —— 完整的三轮审计史见 docs/spec.md §4.3.1。

两类错误，方向相反，严重程度也不同
----------------------------------
**漏标**（更危险，本站最小读者 10 岁）：第一版只审了「标了的该不该标」，
结果漏掉 299 条人为暴力，包括甘地遇刺 —— 因为词表有「枪杀」没有「枪击」。

**误标**（是价值判断错误）：中文没有词边界，而且同一个词会同时出现在
暴行和反对暴行的叙述里：

  种族  50 条 —— 其中约 24 条是民权史：废除种族隔离、《民权法案》、
                  图图获诺贝尔和平奖、消除种族歧视国际日
  死刑  51 条 —— 其中 10 条是**废除**死刑：法国、英国、加拿大、香港
  灭绝  13 条 —— 含《防止及惩治灭绝种族罪公约》，以及白鲟物种灭绝

把「南非废除种族隔离」标成需家长陪读，是把人类的进步误标成不宜儿童。

豁免必须按词生效
----------------
天灾豁免只压「袭击」，工业事故豁免只压「爆炸」，机型名豁免只压「轰炸」。
一刀切的话「地震后发生枪击」「弹药船爆炸」会被一起放过。

判定只读 `t`（正文）。不碰 tag，不改正文一个字 —— §4.3 还要求
「措辞与语境」，那是编辑工作，需要人来做，不该由脚本顺手改。
"""
import json
import glob
import re
import sys

# ── 第一段：暴力/死亡命中 ──────────────────────────────────
# 每个词都经过全量实测（见 docs/spec.md §4.3 的审计表）。
#
# 第二轮补的词（第一版漏标 299 条人为暴力，全是这里缺的）：
#   枪击 —— 第一版只有「枪杀」。甘地「遭枪击死亡」因此漏标，
#           是全站最重要的条目之一。
#   袭击 爆炸案 纵火 空袭 轰炸 击落 炸弹 恐怖袭击 —— 整类缺失。
#
# 刻意**不收** 战役/起义/政变/叛乱/内战：实测会再多 820 条，
# 总量到 12.1%，把「第三次长沙战役」这类普通军事史全卷进来。
# 陪读提示出现得太频繁就等于没有提示。
VIOLENT = re.compile(
    r'屠杀|虐杀|活埋|斩首|凌迟|焚城'
    r'|刺杀|遇刺|行刺|暗杀'
    r'|处决|枪决|枪杀|绞刑|火刑|断头台|问吊'
    r'|杀害|杀死|灭门'
    r'|自杀式|殉情|自尽|服毒|切腹'
    r'|集中营|毒气|酷刑|强奸|轮奸|暴行'
    r'|种族清洗|种族灭绝|大清洗'
    r'|核试验|核爆|原子弹'
    # ── 第二轮补充 ──
    r'|枪击|扫射|枪战'
    r'|恐怖袭击|恐怖攻击|恐怖主义|恐袭'
    r'|炸弹|爆炸|爆炸案|连环爆炸|爆炸袭击'
    r'|纵火|劫机'
    r'|空袭|轰炸|炮击|炮轰|击落'
    r'|袭击'                      # 放最后：前面更具体的词优先命中，便于看原因
    # 人质/劫持类 —— 别斯兰校园围困（396 人死亡）用上面任何词都命中不了：
    # 它写的是「攻入…武装分子…占领…一所中学…人质与恐怖分子共396人死亡」。
    r'|人质|劫持|绑架|武装分子|恐怖分子'
    # 第三轮补：宾汉顿枪击案（14 人死亡）写的是「枪手…开枪」，
    # 既没有「枪击」也没有「枪杀」，整句一个词都命中不了。
    r'|枪手|开枪|持枪'
)

# ── 第二段：豁免 ─────────────────────────────────────────
# 第一版把豁免词当成「句中出现即豁免」，结果把这些**漏标**了：
#     马丁·路德·金遇刺      ← 被「民权」豁免
#     苏联红军攻占奥斯威辛   ← 被「释放」豁免
#     纳吉·伊姆雷被处决     ← 被「公约」豁免（公约在前半句讲他的政绩）
#     镇反「要大杀几批」     ← 被「报告」豁免
# 教训：豁免不能看「句中有没有这个词」，要看**句子在讲什么**。
# 暴行发生了就是发生了，叙述里提到民权、释放、公约都不改变这一点。
#
# 因此豁免一律要求「贴着暴力词出现」，并且 (f)(h)(i) 三条还要求
# 把该短语抠掉后全句不再有其它暴力词。下面 (a)–(i) 每一条都对应
# 一类实测出来的误标，条数见 docs/spec.md §4.3.1 的审计表。

# (a) 制度性否定：必须紧贴暴力词，如「废除死刑」「禁止…种族隔离」
#     「停止炮击」是第三轮实测补的 —— 《告台湾同胞书》宣布**停止**对
#     金门炮击，句子讲的是停火，不是开火。
ABOLITION = re.compile(
    r'(?:废除|取消|禁止|消除|结束|停止)[^。；]{0,6}'
    r'(?:死刑|种族隔离|种族歧视|酷刑|奴隶)'
    r'|(?:死刑|种族隔离|酷刑)[^。；]{0,4}(?:废除|取消|禁止)'
    r'|(?:停止|终止|结束|停火)[^。；]{0,8}(?:炮击|炮轰|轰炸|空袭|袭击)'
)

# (b) 物种灭绝：生物学语境，与人类暴力无关
SPECIES = re.compile(r'(?:濒危|物种|红色名录|白鲟|渡渡鸟).{0,20}灭绝'
                     r'|灭绝.{0,10}(?:物种|红色名录)')

# (c) 纯纪念/条约：全句既无伤亡数字也无暴行动词主干
TREATY_ONLY = re.compile(r'^[^。]{0,40}(?:公约|条约|协定)[^。]{0,20}(?:通过|生效|签署)')

# (d) 条约/协定本身的名字里带暴力词 —— 第二轮补词后才暴露出来。
#     例：《全面禁止核试验条约》《部分禁止核试验条约》。叙述的是限制，
#     不是进行。注意只认「书名号内含禁止/限制」或「签署/谈判/通过条约」，
#     不能宽到把「北约轰炸南斯拉夫」也放过（那里的「公约」只是组织名）。
TREATY_NAME = re.compile(
    r'《[^》]{0,20}(?:禁止|限制|不扩散)[^》]{0,20}》'
    r'|(?:签署|缔结|谈判|批准|通过)[^。]{0,16}(?:禁止|限制)[^。]{0,16}(?:条约|公约|协定)'
    r'|条约[^。]{0,10}限制[^。]{0,10}(?:核爆|核试验)'
    r'|限制[^。]{0,12}(?:核爆|核试验)[^。]{0,12}规模'
)

# (e) 遗址/纪念馆：集中营改为纪念馆，讲的是纪念而非关押
MEMORIAL = re.compile(r'(?:集中营|战场|遗址)[^。]{0,8}(?:改为|辟为|列为|成为)[^。]{0,8}'
                      r'(?:纪念馆|纪念地|遗址|博物馆|世界遗产)')

# (f) 天灾用了「袭击」这个动词 —— 第二轮加入「袭击」后才暴露。
#     「地震袭击夏威夷」「飓风卡崔娜袭击路易斯安那」是自然灾害，
#     §4.3 讲的是屠杀/刺杀/处决这类人为暴力，天灾不在范围内。
#     实测 13 条。注意：这条豁免只压「袭击」，不压其它暴力词 ——
#     「地震后发生抢劫枪击」仍该标。
NATURAL_HIT = re.compile(
    r'(?:地震|台风|飓风|龙卷风|海啸|风暴|暴雪|暴雨|沙尘暴|寒流|热浪|洪水|'
    r'冰雹|雪崩|泥石流|火山)[^。]{0,12}袭击'
)

# (g) 专有名词里含暴力词 —— 实测只有「台北暗杀星」（电竞队名）一例。
#     列成白名单而不是写通用规则：一个特例不值得为它放宽判定。
PROPER_NOUN = re.compile(r'暗杀星')

# (h) 工业/交通事故里的「爆炸」—— 第二轮加入「爆炸」后暴露，实测 12 条。
#     化工厂、煤矿、货轮、煤气、热气球爆炸是事故，不是人为暴力。
#     与天灾豁免同理：只压「爆炸」，其它暴力词不受影响。
#     注意：句中若有恐怖/军事信号，由下面的 ATTACK_CONTEXT 反压，
#     这样伦敦地铁爆炸、奥克拉荷马联邦大楼、弹药船爆炸仍会标记。
INDUSTRIAL = re.compile(
    r'化工厂|化学厂|炼油|油库|油罐|油轮|货轮|渡轮|煤矿|煤尘|瓦斯|矿井'
    r'|煤气|天然气|可燃气体|液化气|管道|输气|锅炉|变电|电车|热气球'
    r'|工厂|车间|仓库|烟花|鞭炮|弹药库|军火库|金属制品|开发区'
)

# 恐怖/军事信号 —— 出现这些就不是事故，INDUSTRIAL 豁免失效
ATTACK_CONTEXT = re.compile(
    r'恐怖|枪手|武装分子|自杀式|人质|劫持|占领|袭击|空袭|轰炸'
    r'|大使馆|领事馆|联邦大楼|世界贸易中心|清真寺|教堂|市集|医院|地铁'
    r'|战争|军港|军方|部队|弹药'
)

# (i) 「轰炸机」作机型名出现（试飞/服役/研制），不是轰炸行为。实测 6 条：
#     B-2 隐形轰炸机试飞成功、轰-5 试飞成功、蚊式轰炸机首次试飞…
#     这是航空史，不是暴力事件。
BOMBER_NAME = re.compile(
    r'轰炸机[^。]{0,16}(?:试飞|首飞|服役|列装|研制|问世|交付|退役|亮相|下线|停止生产)'
    r'|(?:试飞|首飞|服役|列装|研制|制造|问世|设计)[^。]{0,16}轰炸机'
)


def _has_casualty(text):
    """句中是否出现伤亡 —— 有就不豁免，无论前后文说什么。"""
    return bool(re.search(r'死亡|身亡|丧生|遇害|死难|伤亡|被杀|\d+\s*人死', text))


def is_sensitive(text):
    """返回 (是否标记, 原因) —— 原因用于人工复核时快速判断。"""
    m = VIOLENT.search(text)
    if not m:
        return False, ''
    hit = m.group(0)

    # 专有名词白名单最优先：队名里的「暗杀」不是暴力事件
    if PROPER_NOUN.search(text) and hit in ('暗杀', '刺杀'):
        return False, f'命中「{hit}」但属专有名词：{PROPER_NOUN.search(text).group(0)}'

    # 天灾豁免只针对「袭击」这一个动词 —— 其它暴力词不受影响。
    # 「地震袭击某地」不标；但「地震后发生枪击」仍要标，
    # 所以要把天灾短语抠掉再看剩下的文本还有没有暴力词。
    if hit == '袭击':
        nat = NATURAL_HIT.search(text)
        if nat and not VIOLENT.search(text.replace(nat.group(0), '')):
            return False, f'命中「袭击」但属天灾：{nat.group(0)[:14]}'

    # 工业/交通事故的「爆炸」：化工厂、煤矿、货轮等。
    # 但若句中有恐怖/军事信号（大使馆、人质、弹药、恐怖分子…），
    # 说明不是事故，豁免失效。
    if hit in ('爆炸', '爆炸案', '炸弹'):
        ind = INDUSTRIAL.search(text)
        if ind and not ATTACK_CONTEXT.search(text):
            return False, f'命中「{hit}」但属工业事故：{ind.group(0)}'

    # 「轰炸机试飞」是航空史，不是轰炸行为
    if hit == '轰炸':
        bn = BOMBER_NAME.search(text)
        if bn and not VIOLENT.search(text.replace(bn.group(0), '')):
            return False, f'命中「轰炸」但属机型名：{bn.group(0)[:16]}'

    # 有伤亡就一定标，任何豁免都压不住
    if _has_casualty(text):
        return True, f'命中「{hit}」且有伤亡'

    for rx, label in ((SPECIES, '物种灭绝'),
                      (ABOLITION, '制度性废除'),
                      (TREATY_NAME, '条约名含暴力词'),
                      (MEMORIAL, '遗址纪念馆'),
                      (TREATY_ONLY, '仅条约通过')):
        ex = rx.search(text)
        if ex:
            return False, f'命中「{hit}」但属{label}：{ex.group(0)[:20]}'
    return True, f'命中「{hit}」'


def main():
    apply = '--apply' in sys.argv
    verbose = '--verbose' in sys.argv

    flagged = exempted = 0
    changed_files = 0
    samples, exempt_samples = [], []

    for path in sorted(glob.glob('data/otd/*.json')):
        day = json.load(open(path, encoding='utf-8'))
        dirty = False
        for group in ('selected', 'events'):
            for item in day[group]:
                hit, why = is_sensitive(item['t'])
                if hit:
                    flagged += 1
                    if len(samples) < 12:
                        samples.append((path[-10:-5], group, why, item['t']))
                    if item.get('sensitive') is not True:
                        if apply:
                            item['sensitive'] = True
                        dirty = True
                else:
                    if why:          # 命中但被豁免
                        exempted += 1
                        if len(exempt_samples) < 10:
                            exempt_samples.append((why, item['t']))
                    # 之前误标过就撤掉，保证脚本可重复运行
                    if item.get('sensitive') is not None:
                        if apply:
                            item.pop('sensitive', None)
                        dirty = True
        if dirty:
            changed_files += 1
            if apply:
                # 紧凑单行，与 gen_otd.py 的写法一致
                with open(path, 'w', encoding='utf-8') as fh:
                    json.dump(day, fh, ensure_ascii=False, separators=(',', ':'))

    print(f"{'已写入' if apply else '预演（未写入）'}")
    print(f"  标记 sensitive : {flagged} 条")
    print(f"  命中但豁免     : {exempted} 条")
    print(f"  涉及文件       : {changed_files} 个")

    if verbose:
        print('\n── 标记样本 ──')
        for d, g, why, t in samples:
            print(f'  {d} [{g}] {why}\n      {t[:72]}')
        print('\n── 豁免样本（这些**不该**标）──')
        for why, t in exempt_samples:
            print(f'  {why}\n      {t[:72]}')


if __name__ == '__main__':
    main()
